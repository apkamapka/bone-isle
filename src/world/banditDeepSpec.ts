/**
 * Bandit Deep -1 — the cellars under the Gallows Coast.
 *
 * Traced from `piwnica_bandit.tmx` (105x100). Collision comes from the two wall
 * layers; the shadow layer is decoration and is deliberately NOT solid, exactly
 * as its name in Tiled says. Everything standing on the floor — rock, bones,
 * boulders, totems, the camps and every creature post — was scattered over the
 * traced ground and written down here, so nothing is rolled at load time.
 *
 * THE SIX LADDERS. This floor is the same 105x100 as the island above it, and
 * the ladders sit on the SAME tile coordinates as the six holes up there: go
 * down at (26,54) and you come up at (26,54). Five of the six landed on open
 * cave; the fifth had rock on its square and moved one tile north, which is the
 * whole of the difference between the two maps. Because six pads on this floor
 * all point back at the same island, `travelTo` picks the one nearest to where
 * the player stood rather than the first in the list — otherwise every descent
 * on the island would spit you out of the north-eastern ladder.
 *
 * WHO LIVES HERE. The upper half of the human ladder, lower slice: mercenary
 * through gladiator, levels 16 to 28. Barbarian, raider, warlord and chieftain
 * are held back for -2; the Black Knight for -3.
 *
 * The floor is ranked by distance from the NEAREST LADDER, not by distance from
 * the hole down to -2. Six entrances means six first impressions, and ranking
 * along the way down inverted them: the south-western hole is the hardest on
 * the island and would have dropped you among mercenaries, while the gentlest
 * hole up top opened onto amazons. Ranking from the ladders makes every one of
 * the six a soft landing and hardens the floor as you push inward — which puts
 * the gladiators around the middle of the map anyway, because that is where the
 * hole to -2 was cut.
 *
 * Seven camps are dug into it: tents, fires, a well and a totem apiece, with a
 * pair of the heavier ranks posted around each. No trees and no buildings —
 * this is a cellar, and a gang that lives in one lives out of canvas and stone.
 *
 *   1..6 ladders back up to the Gallows Coast   D descent to -2
 *   # rock wall   = cave floor
 *   R rock   F campfire   N tent   W well   Y skull totem
 *   Q q black boulder (two variants)   o bones
 *   creatures: e mercenary  j corsair  w wildWarrior  z amazon
 *              u hunter  l gladiator
 */
