/**
 * BONETOWN — six islands, traced from `city2.tmx` (106x106).
 *
 * The terrain art is the Tiled export (`public/town-terrain.png`); this file
 * carries COLLISION and everything that stands on the ground, derived from the
 * same export so you can walk exactly where land is drawn. A shore tile more
 * than a third water is `~`, which is why the coast reads a shade tighter than
 * it looks.
 *
 * Two grids: `rows` says what stands on each square, `floor` what the square is
 * made of. The town square, the bridge decks and the two shadow circles are
 * `:`; everything else ashore is `.`. A feature glyph defaults to grass
 * beneath it, so without the second grid every building on the square would
 * report meadow to the minimap.
 *
 * THE SIX ISLANDS, and how they are strung together:
 *
 *   A  north-west   x 5..50,  y 4..36    wild — cutthroat, deserter
 *   B  north-east   x 49..99, y 3..55    wild — beggar, vagrant, thief
 *   C  centre       x 34..75, y 32..68   THE TOWN. Paved square, gate home
 *   D  west         x 10..31, y 38..60   THE SAGE. Trapdoor to his cellar
 *   E  south-east   x 6..100, y 56..103  wild — poacher, bandit, smuggler
 *   F  south-west   x 7..36,  y 59..94   wild — brigand, highwayman
 *
 * Five bridges: A-B, B-C, D-C, C-E, E-F. From the town that is one crossing to
 * B and to E, two to A (through B) and two to F (through E), and the creature
 * ladder is laid along exactly that: the lightest camp is the one nearest the
 * bridge you arrived by, on the island nearest the town.
 *
 * C and D are the haven — `safeRects` below — plus the bridge between them,
 * because both its ends are town. The bridges to B and to E are NOT in it: a
 * haven reaching across them would put a safe square on the far shore, one
 * step from a camp.
 *
 * THE TOWN IS BUILT OF ONE FAMILY, ON PURPOSE. The prop set holds two of
 * everything — warm plaster beside grey stone, and, worse, two human scales
 * whose doorways differ by a factor of two. The first draft of this map used
 * one of each and read as a sample sheet: a chapel whose door was shorter than
 * the player stood next to a manor whose door was not. So the town is warm
 * plaster only, at the large scale only, out of nine kinds repeated —
 * `manor`, `inn`, `apothecary`, `temple`, `shoprow`, `storefront`,
 * `shophouse`, `guildhall`, `bank` — with `greattemple` once, at the head of
 * the square, five tiles deep against everything else's three so the eye has
 * somewhere to land. The grey-stone half of the pack is unused here and is
 * coherent WITH ITSELF, which is what it is being saved for.
 *
 * The one exception is the sage's `observatory`, and it is an exception on the
 * same principle: it stands on his island, where there is no other building
 * within sight of it to clash with.
 *
 * Camp centres are chosen, not searched for. Picking them by percentile of
 * distance from the bridge put five of ten within thirteen tiles of the edge
 * of the map and left the middles of the islands bare; these are read off the
 * island shapes and strung along the way you would walk in. Sizes run five to
 * eight and the layouts rotate through three shapes, so ten camps do not read
 * as one camp stamped ten times.
 *
 * The scatter — 275 trees, 140 rock, 32 of mushroom and bone — is on GRASS
 * only, so the square stays swept and the ring of green frames the town.
 * Nothing tall stands within two tiles of the sea, because the coastline is a
 * fringe of grass over water and a trunk planted on it looks like it is
 * wading; nothing stands within one tile of a doorway or a camp, so no facade
 * is hidden and nothing is fenced in. Checked by flood fill: every creature,
 * every townsperson and both gates are reachable on foot from the gate home,
 * with trees and rock counted as walls.
 */
