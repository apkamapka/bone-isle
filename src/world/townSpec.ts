/**
 * BONETOWN — six islands, traced from `city2.tmx` (106x106).
 *
 * The terrain art is the Tiled export (`public/town-terrain.png`); this file
 * carries COLLISION and everything that stands on the ground, derived from the
 * same export so you can walk exactly where land is drawn. A shore tile that is
 * more than a third water is `~`, which is why the coast reads a shade tighter
 * than it looks.
 *
 * Two grids, the Bone Reach's arrangement: `rows` says what stands on each
 * square, `floor` what the square is made of. The roads, the bridge decks and
 * the two shadow circles are `:` and everything else ashore is `.`, and a
 * feature glyph defaults to grass beneath it — so without the second grid every
 * building on a road would report meadow to the minimap.
 *
 * THE SIX ISLANDS, and how they are strung together:
 *
 *   A  north-west   x 5..50,  y 4..36    wild — cutthroat, deserter
 *   B  north-east   x 49..99, y 3..55    wild — beggar, vagrant, thief
 *   C  centre       x 34..75, y 32..68   THE TOWN. Roads, NPCs, gate home
 *   D  west         x 10..31, y 38..60   THE SAGE. Trapdoor to his cellar
 *   E  south-east   x 6..100, y 56..103  wild — poacher, bandit, smuggler
 *   F  south-west   x 7..36,  y 59..94   wild — brigand, highwayman
 *
 * Five bridges: A-B, B-C, D-C, C-E, E-F. From the town that is one crossing to
 * B and to E, two to A (through B) and two to F (through E), and the creature
 * ladder is laid along exactly that: the lightest camp is the one nearest the
 * bridge you arrived by, on the island nearest the town.
 *
 * C and D are the haven — `safeRects` below, one rectangle at a time, plus the
 * bridge between them because both its ends are town. The bridges to B and to E
 * are NOT in it: a haven that reached across them would put a safe square on
 * the far shore, one step from a camp, which is the oldest way to make a
 * hunting ground pointless.
 *
 * Both gates sit on the black circles the map paints for them, four squares
 * each, dead centre: the way home on C at (72,49), the trapdoor into the Time
 * Sage's cellar on D at (18,46).
 *
 * The scatter — 311 trees, 139 rock, 30 of mushroom and bone — obeys the Bone
 * Reach's two rules. Nothing tall stands within two tiles of the sea, because
 * the coastline is a fringe of grass over water and a trunk planted on it looks
 * like it is wading; and nothing stands within one tile of a doorway or a camp,
 * so no facade is hidden and nothing is fenced in. It was then checked by flood
 * fill: every creature, every townsperson and both gates are reachable on foot
 * from the gate home, with trees and rock counted as walls.
 */
