/**
 * BONETOWN — six islands, traced from `city2.tmx` (106x106).
 *
 * The terrain art is the Tiled export (`public/town-terrain.png`); this file
 * carries COLLISION and everything that stands on the ground, derived from the
 * same export so you can walk exactly where land is drawn. A shore tile more
 * than a third water is `~`, which is why the coast reads a shade tighter than
 * it looks.
 *
 * Two grids: `rows` says what stands on each square, `floor` what the square is
 * made of. The town square, the bridge decks and the two shadow circles are
 * `:`; everything else ashore is `.`. A feature glyph defaults to grass
 * beneath it, so without the second grid every building on the square would
 * report meadow to the minimap.
 *
 * THE SIX ISLANDS, and how they are strung together:
 *
 *   A  north-west   x 5..50,  y 4..36    wild — cutthroat, deserter
 *   B  north-east   x 49..99, y 3..55    wild — beggar, vagrant, thief
 *   C  centre       x 34..75, y 32..68   THE TOWN. Paved square, gate home
 *   D  west         x 10..31, y 38..60   THE SAGE. Trapdoor to his cellar
 *   E  south-east   x 6..100, y 56..103  wild — poacher, bandit, smuggler
 *   F  south-west   x 7..36,  y 59..94   wild — brigand, highwayman
 *
 * Five bridges: A-B, B-C, D-C, C-E, E-F. From the town that is one crossing to
 * B and to E, two to A (through B) and two to F (through E), and the creature
 * ladder is laid along exactly that: the lightest camp is the one nearest the
 * bridge you arrived by, on the island nearest the town.
 *
 * C and D are the haven — `safeRects` below — and so are the DECKS of all
 * three bridges that lead into them. The decks used to be left out, and the
 * consequence showed up on screen within a minute: nothing may step into the
 * haven, so a creature walked the whole seven-tile deck of the south bridge
 * and stood one square short of the paving, and crossing into town was a
 * fight. A bridge with a safe end and a hostile middle is not a gate, it is an
 * ambush. The two decks between wild islands — A-B in the north, E-F in the
 * south — stay wild; both their ends are hunting ground and there is nothing
 * there to protect.
 *
 * THE SQUARE IS EMPTY, and that is deliberate rather than unfinished. Nothing
 * stands on the paving but four market stalls; the `scenery` map below has no
 * building in it at all.
 *
 * The history is worth keeping, because the prop set is still in `public/` and
 * whoever fills this square next will hit the same two traps. The pack holds
 * two of everything — warm plaster beside grey stone, and two human scales
 * whose doorways differ by a factor of two. A first draft used one of each and
 * read as a sample sheet: a chapel whose door was shorter than the player
 * stood beside a manor whose door was not. A second draft used one family at
 * one size and still read as a row of models, because every prop shipped small
 * — so all thirty were redrawn at twice the size, and a manor that had been
 * four tiles by three became eight by six. That is the state the art is in:
 * doubled, coherent, and unused here.
 *
 * The stalls did NOT double and are the one thing still standing. A stall is a
 * table under a canvas, so it was already person-sized, which is exactly why
 * it survives on a square where nothing else did.
 *
 * Camp centres are chosen, not searched for. Picking them by percentile of
 * distance from the bridge put five of ten within thirteen tiles of the edge
 * of the map and left the middles of the islands bare; these are read off the
 * island shapes and strung along the way you would walk in.
 *
 * THE CREATURES ARE EIGHT TILES APART, EVERY ONE OF THEM. This is the low half
 * of the ladder — the ground a level 1 learns to fight on — and a level 1 has
 * no answer to two at once. A creature notices you at six tiles and nothing
 * wakes its neighbours (combat sets `aggroT` on the one that was hit and on
 * nothing else), so standing next to one post puts you at |A-B| - 1 from the
 * next: seven tiles already keeps it asleep and eight leaves a tile of slack
 * for backing off mid-fight. The rule is global rather than per camp, because
 * two camps whose edges met would pull just as badly as one camp packed tight.
 *
 * The camps are the landmarks and the countryside between them is filled: once
 * they are down, every wild island is walked in a fixed shuffled order and a
 * creature dropped wherever the eight-tile rule still allows one, taking its
 * kind from the NEAREST CAMP CENTRE so the fill does not blur the ladder. That
 * is what takes the map from sixty-six posts to eighty-four, against a hard
 * ceiling of about ninety-one — 5,854 tiles of wild grass, one post per
 * sixty-four at this spacing. The map is now as full as its own spacing rule
 * permits; the only way to more creatures is fewer tiles between them.
 *
 * That spacing is what sets the camp sizes, not the other way round. Each camp
 * is packed as a RING of radius nine around its fire — about fifty-seven tiles
 * round, which is seven posts at eight apart — capped at fourteen so a camp
 * squeezed onto narrow ground stays a camp instead of stringing itself across
 * an island. Where the headland is thin it simply holds fewer: four
 * highwaymen, three wild warriors to a pocket. Sixty-six posts in all, where
 * the packed version had eighty-five; that is the price of fighting them one
 * at a time and it is worth paying.
 *
 * The scatter — 459 trees, 230 rock, 35 of mushroom and bone — is on GRASS
 * only, so the square stays swept and the ring of green frames the town.
 * Nothing tall stands within two tiles of the sea, because the coastline is a
 * fringe of grass over water and a trunk planted on it looks like it is
 * wading; nothing stands within one tile of a doorway or a camp, so no facade
 * is hidden and nothing is fenced in. Checked by flood fill: every creature,
 * every townsperson and both gates are reachable on foot from the gate home,
 * with trees and rock counted as walls.
 */
