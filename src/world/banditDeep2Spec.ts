/**
 * Bandit Deep -2 — the deep cells, and the end of the human ladder.
 *
 * Traced from `piwnica_bandit-2.tmx` (105x100). Collision comes from the two
 * wall layers; the shadow layer is decoration and is deliberately NOT solid,
 * exactly as its name in Tiled says. Everything on the floor was scattered over
 * the traced ground and written down here — nothing is rolled at load time.
 *
 * ONE WAY IN. The ladder back up to -1 stands on (57,40), the very square the
 * hole on -1 was cut into: all three floors of this place share one 105x100
 * grid, so a hole and the ladder under it have the same coordinates. Unlike -1,
 * which has six entrances, this floor has one — so it is ranked outward from
 * that single ladder, weakest at the foot of it and hardest the further in you
 * push.
 *
 * WHO LIVES HERE. The top of the human ladder and nothing else: barbarian,
 * raider, warlord and chieftain, levels 30 to 40. Ninety-nine posts, and with
 * them every one of the twenty human ranks in the bestiary finally spawns
 * somewhere in the game.
 *
 * THE WAY DOWN. `D` in the south-west corner drops to -3, the black cell, where
 * the Black Knight waits. It is not left standing in an empty corridor: five
 * chieftains and warlords are posted around it. That is the Orc Deep's rule for its hoard — a floor's last thing is
 * guarded by the floor's worst thing, not by distance.
 *
 * THE WESTERN WING. It used to be a sealed pocket. The first drawing boxed the
 * western corridor in between the cave edge and the wall at x=14-15, with the
 * bands at y=42-43 and y=86-87 closing the ends and no door cut anywhere: 297
 * squares of painted floor with no way in. They were left empty and marked as
 * rock, because punching the wall out in THIS file and not in the drawing would
 * only have walked the player through two squares of painted stone — the
 * terrain export is the picture, and the picture wins.
 *
 * The map has since been redrawn with doorways at y=53-54 and y=80-82, and the
 * re-export changed exactly those 297 squares and not one other on the floor.
 * So the wing was sewn in rather than the floor re-traced: every post and every
 * prop already on it stayed where it was put. What went into the wing follows
 * the floor's own rules and not a new one — an EIGHTH CAMP measured off the
 * seven already dug (three tents, three fires, a well, two totems, boulders,
 * rock and bones), and six posts, which holds the floor at 66 squares per
 * creature against the 67 it ran at before. They are ranked by the same
 * distance bands the rest of the floor uses: the wing sits 63 to 103 steps out,
 * which is warlord ground, with its deep end reaching into the chieftains'.
 *
 *   1 ladder back up to -1   D descent to -3
 *   # rock wall   = cave floor
 *   R rock   F campfire   N tent   W well   Y skull totem
 *   Q q black boulder (two variants)   o bones
 *   creatures: b barbarian  r raider  v warlord  c chieftain
 */
