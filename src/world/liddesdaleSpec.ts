/**
 * Liddesdale - the Bloody Valley. The Time Sage's first mission ground.
 *
 * Traced from `redcaplewyspa.tmx` (80x80), and DRAWN from
 * `public/liddesdale-terrain.png`, which is that file's own "Export as Image"
 * at native tile size. The picture is the map's whole look; the glyph grid
 * below is only what the picture cannot say - collision, portals, posts.
 *
 * WHY THE FLOOR GRID IS ALL PEAT. Every land square is `:`. The exported
 * picture covers it, so this only shows on the minimap and in the fallback
 * bake if the image ever fails to load - but bare bog is what the art is, and
 * a green sward underneath would be the one thing on the island not dying.
 *
 * THE FORTY MUD PATCHES ARE NOT IN THIS GRID AT ALL. The export paints them
 * and they are flat, so they are walkable and the grid has nothing to say
 * about them. This file got that wrong twice before settling: first by drawing
 * an engine boulder on each one (two rocks, two art styles, one square), then
 * by sealing the footprint as `solids`. Both were wrong for the same reason -
 * the identical layer in the lair below is FLOOR, and one flat slick cannot be
 * a wall upstairs and a puddle downstairs.
 *
 * NO LIVE TREES. Not one `T`, which is the only thing separating this scatter
 * from the Gallows Coast's. Dead wood, felled wood, stone, bog mushrooms and
 * bones - and the bones thicken toward the hole, because of whose ground it is.
 *
 * WHO LIVES HERE. The Border reivers, levels 8 to 15: smuggler, cutthroat,
 * deserter, brigand, highwayman. A tight five-rank band rather than the
 * Gallows Coast's full ladder, because this is one mission's ground and a
 * character arrives on it already level ten. Ranked by WALK distance from the
 * pad and not by straight line - the bog wraps around two bays, and a point
 * ten tiles away across open water is a hundred tiles of walking. Smugglers
 * where you land in the north-west, highwaymen over the hole in the deep
 * south. No two posts within eight tiles, so every pull is a single one.
 *
 * Seven reiver camps are pitched on it - a fire, two tents, a march-stone and
 * a pile of bones apiece - set away from the posts so a camp never doubles a
 * pull.
 *
 * NINE STANE RIG, rows 12-18 around column 16. A ring of nine stones with a
 * fire burning in the middle of it, eight tiles south-east of where the pad
 * puts you down, which makes it the first thing on the island the player walks
 * into. It is the place in the chronicle: the stone circle above Hermitage
 * where de Soulis' own tenants wrapped him in lead and boiled him, and the
 * real Nine Stane Rig is a real ring on a real ridge above the real castle.
 *
 * NINE, exactly, and a smoke test counts them. The number is the name and the
 * name is the only reason a player who reads the chronicle can stand in this
 * thing and recognise it — eight stones or ten would be a different place. The
 * one pre-existing stone that fell on the ring's own radius was cleared for
 * the same reason, because a tenth stone at ring distance is a tenth stone.
 *
 * The fire in the middle is a campfire and campfires seal nothing, so the
 * player can walk in and stand where they cooked him. That is the whole point
 * of putting it there rather than a scorch mark: it is still lit, seven
 * hundred years on, and nobody is tending it.
 *
 *   P pad back to the cellar (2x2)   D down to the redcap's lair
 *   V dead tree   v felled wood   R stone
 *   N tent   F campfire   Y march-stone   M bog mushrooms   o bones
 *   creatures: s smuggler  c cutthroat  d deserter  g brigand  h highwayman
 */
