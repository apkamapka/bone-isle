/**
 * Liddesdale — the Bloody Valley. The Time Sage's first mission ground.
 *
 * Traced from `redcaplewyspa.tmx` (80x80). The coastline, the inland lake, the
 * two bays and all forty rock clusters come from that file; the pad, the hole
 * down, the creature posts and the scatter were laid over the traced land and
 * written down here, so this grid is the whole truth about the island.
 *
 * WHY IT IS DIRT AND NOT GRASS. Every land square is `:` in the floor grid.
 * The terrain art is bare peat and standing water — Hermitage was raised on
 * ground so soft that the bog was its only defence — and a green sward under
 * it would have been the one thing on the island that is not dying.
 *
 * THE ROCKS. Tiled draws each of the forty outcrops as a 3x2 slab, a 2x3
 * standing pillar or one 4x3, and the engine's boulder is a one-tile prop. So
 * each cluster became ONE boulder on its centre square and the rest of the
 * footprint went back to open ground: sealing the whole block would have
 * walled off ground the picture itself shows as walkable. Wide slabs are
 * `q`, standing pillars `Q`.
 *
 * NO LIVE TREES. Not one `T` on the island, which is the only thing that
 * separates this scatter from the Gallows Coast's. Dead wood, felled wood,
 * stone, bog mushrooms and bones — and the bones thicken toward the hole,
 * because of who has been eating down there.
 *
 * WHO LIVES HERE. The Border reivers, levels 8 to 15: smuggler, cutthroat,
 * deserter, brigand, highwayman. A tight five-rank band rather than the
 * Gallows Coast's full ladder, because this is one mission's ground and a
 * character arrives on it already level ten. Ranked by WALK distance from the
 * pad and not by straight line — the bog wraps around two bays, and a point
 * ten tiles away across open water is a hundred tiles of walking. Smugglers
 * where you land in the north-west, highwaymen over the hole in the deep
 * south, and a legible slope between. No two posts stand within eight tiles of
 * each other, so every pull is a single one.
 *
 * Seven reiver camps are pitched on it — a fire, two tents, a march-stone and
 * a pile of bones apiece — set away from the posts so a camp never doubles a
 * pull.
 *
 *   P pad back to the cellar (2x2)   D down to the redcap's lair
 *   V dead tree   v felled wood   R stone   Q q boulder (pillar, slab)
 *   N tent   F campfire   Y march-stone   M bog mushrooms   o bones
 *   creatures: s smuggler  c cutthroat  d deserter  g brigand  h highwayman
 */
