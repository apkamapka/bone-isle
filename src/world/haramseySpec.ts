/**
 * Haramsey - the barrow coast, and the Time Sage's second mission ground.
 *
 * Traced from `Draugr0.tmx` (80x80) and DRAWN from
 * `public/haramsey-terrain.png`, that file's own "Export as Image" at native
 * tile size. The export has two layers and nothing else: sea and land. So
 * unlike Liddesdale, whose picture carries mud, tracks and stonework, this one
 * is a bare moor and EVERY readable thing on the island is a prop this grid
 * plants. That is why the scatter below is heavier than Liddesdale's over
 * almost the same area - 3832 land squares against 3923, and half again as
 * many objects standing on them.
 *
 * NO LIVE TREES, and here that is not a mood, it is the place: Kárr was buried
 * on an island off the Norwegian coast and this ground is meant to read as the
 * North Atlantic. Dead wood, felled wood, stone, black boulders, bog mushrooms
 * and bone.
 *
 * THE FLOOR GRID IS ALL PEAT. Every land square is `:`. The export covers it,
 * so this shows only on the minimap and in the fallback bake - and dark wet
 * ground is what the picture is.
 *
 * THE TWO ENDS. The pad back to the cellar sits on the north-west shoulder at
 * (16,17); the mouth of the howe is at (70,70), which is the single farthest
 * square from it by WALKING - 107 tiles, around two bays. Straight-line
 * distance would have put the hole barely seventy away and on the wrong side
 * of the water.
 *
 * WHO LIVES HERE. The living who came for the same hoard you did and got no
 * further than the moor: hired blades at the water, sea-raiders across the
 * middle, and the wild ones over the hole. Thirty-two posts, none within eight
 * tiles of another, so every pull is a single one, ranked by walk-distance
 * from the pad.
 *
 * IT WAS BARBARIANS AND RAIDERS FIRST, and that was a misjudgement worth
 * writing down. Both are 440-hit-point creatures worth 365 and 420 experience
 * — level-25 weight standing on a level-15 errand, against a character with
 * about three hundred hit points. Radek walked it and said so. The three ranks
 * here run 175 to 250 hit points and 150 to 200 experience, which is roughly
 * half, sits alongside what the Bone Reach fields, and buys a real gradient of
 * three bands instead of two. None of them is Norse; all of them are people
 * with boats, which is as close as the present roster gets.
 *
 * SIX CAMPS - a fire, two tents, a totem and bones apiece - set clear of the
 * posts so a camp never doubles a pull. EIGHT STONE SETTINGS, two boulders and
 * a totem each, placed toward the far end: they are the graves nobody has
 * opened. The bone piles thicken the same way, because whatever came out of
 * the howe did not go north.
 *
 *   P pad back to the cellar (2x2)   D down into Kárr's howe
 *   V dead tree   v felled wood   R stone   Q q black boulder
 *   N tent   F campfire   Y totem   M bog mushrooms   o bones
 *   creatures: m mercenary   c corsair   w wildWarrior
 */
