/**
 * The Gallows Coast — the lawless island behind the Time Sage's Wildlands pad.
 *
 * Traced from `bandyci.tmx` (105x100). Terrain, coastline and collision come
 * from that file; so do the five bridges, the landing pad and all six descents,
 * read straight off its tile and object layers. Everything standing ON the
 * ground — trees, rock, dead wood, camps and creature posts — was scattered
 * over the traced land and then written down here, so this grid is the whole
 * truth about the island and nothing is added at load time.
 *
 * Two grids: `rows` carries what stands on each square, `floor` what each
 * square is made of. Only the five bridge decks and the seven pad/descent
 * mouths are anything but grass or open water, but the grid is stated in full
 * so a deck never reports grass to the minimap or to the fallback baker.
 *
 * WHAT LIVES HERE. This is the human ladder's home, levels 1 to 14 — the ranks
 * the bestiary has never had a hunting ground for. The island is cut into six
 * regions, one per hole dug down to -1, and each region is ranked toward its
 * own descent: the lightest rank keeps the rim, the heaviest stands over the
 * hole. The region holding the landing pad is the exception and is ranked from
 * the PAD instead, weakest first, because what a fresh character meets in his
 * first ten steps matters more than what guards a descent he cannot survive.
 * So: snakes and beggars where you land, highwaymen four bridges away in the
 * south-west, and a legible slope in between.
 *
 * Eight bandit camps sit on it — tents, a fire, a well, a totem or two — one
 * near each descent and two out on the open ground, each with a pair of the
 * region's heaviest rank standing guard. Nothing tall is planted within two
 * tiles of the sea, and the two squares either side of every bridge deck are
 * kept clear, so a boulder can never cork a crossing.
 *
 * The six descents are cut but sealed: the -1 floor is not drawn yet, and each
 * pad refuses travel with a flash message until it is.
 *
 *   P pad back to the cellar (2x2)   @ spawn   1..6 sealed descents to -1
 *   F campfire   Y skull totem   V dead tree   v felled tree
 *   N tent   W well   Q q black boulder (two variants)
 *   T tree   R rock   M mushrooms   o bones   : bridge deck
 *   creatures: k snake  b beggar  a vagrant  t thief  p poacher  n bandit
 *              s smuggler  c cutthroat  d deserter  g brigand  h highwayman
 */
